import { StrictMode } from "react";
import { act, fireEvent, render, screen } from "@testing-library/react";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { createClient, newIntent } from "../api/client";
import type { Incident, IncidentsPage } from "../api/types";
import { createMockRehearsal } from "../demo/mockRehearsal";
import { MockIncidentApi } from "../mock/store";
import { createMockTransport, MOCK_PRINCIPALS } from "../mock/transport";
import { TourDirector } from "./TourDirector";
import type { TourContext, TourStep } from "./script";

const headers = { Authorization: "Bearer mock-organizer" };
const id = "inc-overflow-room-b";
const read = (api: MockIncidentApi) => api.handle({ method: "GET", path: `/incidents/${id}`, headers }).json as Incident;
const background = (api: MockIncidentApi) => (api.handle({ method: "GET", path: "/incidents", headers }).json as IncidentsPage).items.find(item => item.type === "stage_av");
beforeEach(() => vi.useFakeTimers());
afterEach(() => vi.useRealTimers());

it("pauses background transitions through the director and resumes the remaining delay", () => {
  const api = new MockIncidentApi({ principals: MOCK_PRINCIPALS, startHidden: true, backgroundStepMs: 1000 });
  const context: TourContext = { raise: () => api.raise(), raiseBackground: scenario => api.raiseBackground(scenario), wave: () => {}, pause: () => api.pause(), resume: () => api.resume() };
  const step: TourStep = { id: "mic-pause", title: "Mic lost", body: "Inspect the incident", route: "board", identity: "organizer", holdMs: 200_000, enter: ctx => ctx.raiseBackground("stage_av") };
  render(<StrictMode><TourDirector steps={[step]} context={context} onNavigate={() => {}} onIdentity={() => {}} onExit={() => {}} onRestart={() => api.reset()} /></StrictMode>);
  act(() => vi.advanceTimersByTime(400));
  fireEvent.click(screen.getByRole("button", { name: "Pause" }));
  act(() => vi.advanceTimersByTime(90_000));
  expect(background(api)?.state).toBe("plan_proposed");
  fireEvent.click(screen.getByRole("button", { name: "Resume" }));
  act(() => vi.advanceTimersByTime(599));
  expect(background(api)?.state).toBe("plan_proposed");
  act(() => vi.advanceTimersByTime(1));
  expect(background(api)?.state).toBe("approved");
  act(() => vi.advanceTimersByTime(5000));
  expect(background(api)?.state).toBe("resolved");
  api.reset();
});

it("pauses dispatch and evidence replay, including work created while paused", async () => {
  const api = new MockIncidentApi({ principals: MOCK_PRINCIPALS, dispatchDelayMs: 1000, tickMs: 1000 });
  let token = "mock-organizer";
  const client = createClient({ transport: createMockTransport(api), getToken: () => token });
  api.pause();
  await client.applyAction(newIntent(id, { action: "approve", expected_version: 3, payload: { plan_id: "plan-overflow-1" } }));
  await vi.advanceTimersByTimeAsync(90_000);
  expect(read(api).state).toBe("approved");
  api.resume();
  await vi.advanceTimersByTimeAsync(1000);
  token = "mock-venue-staff-01";
  await client.applyAction(newIntent(id, { action: "ack", expected_version: 5, payload: { assignment_id: "assignment-overflow-1", decision: "accepted" } }));
  await vi.advanceTimersByTimeAsync(1000);
  const version = read(api).version;
  api.pause();
  await vi.advanceTimersByTimeAsync(90_000);
  expect(read(api).version).toBe(version);
  api.resume();
  await vi.advanceTimersByTimeAsync(4000);
  expect(read(api).state).toBe("resolved");
  api.reset();
});

it("replays approval and acceptance on a second rehearsal and cancels reset work", async () => {
  const api = new MockIncidentApi({ principals: MOCK_PRINCIPALS, startHidden: true, dispatchDelayMs: 10, tickMs: 10 });
  const driver = createMockRehearsal(api, "mock-organizer", 1000);
  let token = "mock-organizer";
  const client = createClient({ transport: createMockTransport(api), getToken: () => token });
  const first = await driver.command("run");
  api.pause();
  await vi.advanceTimersByTimeAsync(90_000);
  expect((await driver.poll())?.incident_id).toBeNull();
  api.resume();
  await vi.advanceTimersByTimeAsync(1000);
  await client.applyAction(newIntent(id, { action: "approve", expected_version: 3, payload: { plan_id: "plan-overflow-1" } }));
  await vi.advanceTimersByTimeAsync(10);
  token = "mock-venue-staff-01";
  await client.applyAction(newIntent(id, { action: "ack", expected_version: 5, payload: { assignment_id: "assignment-overflow-1", decision: "accepted" } }));
  await vi.advanceTimersByTimeAsync(50);
  expect((await driver.poll())?.phase).toBe("completed");
  const second = await driver.command("run");
  expect(second.id).not.toBe(first.id);
  expect(second.incident_id).toBeNull();
  await vi.advanceTimersByTimeAsync(1000);
  expect((await driver.poll())?.phase).toBe("awaiting_humans");
  expect(read(api)).toMatchObject({ state: "plan_proposed", version: 3, allowed_actions: ["approve"] });
  driver.reset();
  api.reset();
  await driver.command("run");
  driver.reset();
  api.reset();
  await vi.advanceTimersByTimeAsync(5000);
  expect(await driver.poll()).toBeNull();
  expect(api.handle({ method: "GET", path: `/incidents/${id}`, headers }).status).toBe(404);
});
